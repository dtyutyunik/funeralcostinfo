// Generates lib/page-dates.ts from git history: for each page file, the date
// it was first committed (published) and last committed (updated).
// Runs as a prebuild step. If git is unavailable, keeps the committed copy.
import { execSync } from 'node:child_process';
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();

function gitDates(relPath) {
  try {
    const added = execSync(
      `git log --diff-filter=A --format=%cs -- "${relPath}"`,
      { cwd: join(root, '..'), encoding: 'utf8' }
    ).trim().split('\n').filter(Boolean).pop();
    const last = execSync(
      `git log -1 --format=%cs -- "${relPath}"`,
      { cwd: join(root, '..'), encoding: 'utf8' }
    ).trim();
    if (added && last) return { published: added, updated: last };
  } catch {
    // fall through
  }
  return null;
}

const entries = {};
let ok = true;

// Guides: app/guides/<slug>/page.tsx -> /guides/<slug>/
const guidesDir = join(root, 'app', 'guides');
for (const name of readdirSync(guidesDir, { withFileTypes: true })) {
  if (!name.isDirectory()) continue;
  const rel = `site/app/guides/${name.name}/page.tsx`;
  const d = gitDates(rel);
  if (!d) { ok = false; continue; }
  entries[`/guides/${name.name}/`] = d;
}

// Top-level and section pages
const singles = {
  '/': 'site/app/page.tsx',
  '/calculator/': 'site/app/calculator/page.tsx',
  '/methodology/': 'site/app/methodology/page.tsx',
  '/about/': 'site/app/about/page.tsx',
  '/editorial-policy/': 'site/app/editorial-policy/page.tsx',
  '/affiliate-disclosure/': 'site/app/affiliate-disclosure/page.tsx',
  '/privacy/': 'site/app/privacy/page.tsx',
  '/terms/': 'site/app/terms/page.tsx',
  '/contact/': 'site/app/contact/page.tsx',
  '/press/': 'site/app/press/page.tsx',
  '/guides/': 'site/app/guides/page.tsx',
};
for (const [route, rel] of Object.entries(singles)) {
  if (!existsSync(join(root, '..', rel))) continue;
  const d = gitDates(rel);
  if (!d) { ok = false; continue; }
  entries[route] = d;
}

// Templates for state and city pages
for (const [key, rel] of Object.entries({
  'state-template': 'site/app/funeral-costs/[state]/page.tsx',
  'city-template': 'site/app/funeral-costs/[state]/[city]/page.tsx',
})) {
  const d = gitDates(rel);
  if (!d) { ok = false; continue; }
  entries[key] = d;
}

if (!ok || Object.keys(entries).length === 0) {
  console.log('gen-dates: git history unavailable, keeping existing lib/page-dates.ts');
  process.exit(0);
}

const body = `// Generated by scripts/gen-dates.mjs from git history. Do not edit by hand.
// published = date the page file was first committed; updated = last commit date.
export const PAGE_DATES: Record<string, { published: string; updated: string }> = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(root, 'lib', 'page-dates.ts'), body);
console.log(`gen-dates: wrote ${Object.keys(entries).length} page dates`);
